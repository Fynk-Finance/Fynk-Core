#!/usr/bin/env node
// Joins every session log in docs/history/sessions/ into docs/history/PROJECT_HISTORY.md.
// No dependencies. Run with: node scripts/build-history.mjs

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const sessionsDir = join(root, 'docs', 'history', 'sessions')
const outFile = join(root, 'docs', 'history', 'PROJECT_HISTORY.md')

const MODULE_NAMES = {
  M0: 'Foundations',
  M1: 'Identity',
  M2: 'Vault and backup',
  M3: 'Onboarding',
  M4: 'Consents',
  M5: 'Bank and sync',
  M6: 'Accounts',
  M7: 'Transactions',
  M8: 'Savings goals',
  M9: 'Recurring and subscriptions',
  M10: 'Analytics and caps',
  M11: 'AI recommendations',
  M12: 'Notifications',
  M13: 'Compliance and audit',
  M14: 'Infrastructure',
  M15: 'Investment',
  M16: 'Banco Demo',
}

function parseValue(raw) {
  const v = raw.trim()
  if (v.startsWith('[') && v.endsWith(']')) {
    return v.slice(1, -1).split(',').map((s) => s.trim()).filter(Boolean)
  }
  return v.replace(/^["']|["']$/g, '')
}

function parseSession(file) {
  const text = readFileSync(join(sessionsDir, file), 'utf8').replace(/\r\n/g, '\n')
  const match = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/)
  if (!match) throw new Error(`${file}: missing front matter`)
  const meta = {}
  for (const line of match[1].split('\n')) {
    const i = line.indexOf(':')
    if (i > 0) meta[line.slice(0, i).trim()] = parseValue(line.slice(i + 1))
  }
  for (const key of ['date', 'developer', 'github', 'module']) {
    if (!meta[key]) throw new Error(`${file}: missing "${key}" in front matter`)
  }
  if (!/^\d{4}-\d{2}-\d{2}$/.test(meta.date)) throw new Error(`${file}: date must be YYYY-MM-DD`)
  const body = match[2].replace(/<!--[\s\S]*?-->/g, '').trim()
  const titleMatch = body.match(/^#\s+(.+)$/m)
  const title = titleMatch ? titleMatch[1].trim() : file
  const content = body.replace(/^#\s+.+$/m, '').trim()
  return { file, title, content, ...meta, jira: Array.isArray(meta.jira) ? meta.jira : [] }
}

function moduleLabel(m) {
  return MODULE_NAMES[m] ? `${m} ${MODULE_NAMES[m]}` : m.charAt(0).toUpperCase() + m.slice(1)
}

function moduleOrder(m) {
  const n = /^M(\d+)$/.exec(m)
  return n ? Number(n[1]) : 100
}

function groupBy(list, key) {
  const map = new Map()
  for (const s of list) {
    const k = s[key]
    if (!map.has(k)) map.set(k, [])
    map.get(k).push(s)
  }
  return map
}

function demote(content) {
  return content.replace(/^(#{2,5})\s/gm, (_, h) => `${h}### `)
}

const files = readdirSync(sessionsDir).filter((f) => f.endsWith('.md')).sort()
const sessions = files.map(parseSession).sort((a, b) => (a.date + a.file).localeCompare(b.date + b.file))

const byModule = [...groupBy(sessions, 'module').entries()].sort((a, b) => moduleOrder(a[0]) - moduleOrder(b[0]) || a[0].localeCompare(b[0]))
const byDev = [...groupBy(sessions, 'developer').entries()].sort((a, b) => a[0].localeCompare(b[0]))

const first = sessions[0]?.date ?? 'none'
const last = sessions.at(-1)?.date ?? 'none'
const out = []

out.push('# Fynk project history', '')
out.push('Generated by `scripts/build-history.mjs` from `docs/history/sessions/`. Do not edit by hand.', '')
out.push(`${sessions.length} sessions from ${first} to ${last}, by ${byDev.length} ${byDev.length === 1 ? 'developer' : 'developers'}, across ${byModule.length} ${byModule.length === 1 ? 'module or area' : 'modules or areas'}.`, '')

out.push('## Summary by module', '', '| Module | Sessions | Developers | Jira keys | First | Last |', '| --- | --- | --- | --- | --- | --- |')
for (const [m, list] of byModule) {
  const devs = [...new Set(list.map((s) => s.developer))].join(', ')
  const keys = [...new Set(list.flatMap((s) => s.jira))].join(', ') || 'none'
  out.push(`| ${moduleLabel(m)} | ${list.length} | ${devs} | ${keys} | ${list[0].date} | ${list.at(-1).date} |`)
}
out.push('')

out.push('## Summary by developer', '', '| Developer | GitHub | Sessions | Modules |', '| --- | --- | --- | --- |')
for (const [d, list] of byDev) {
  const mods = [...new Set(list.map((s) => s.module))].sort((a, b) => moduleOrder(a) - moduleOrder(b)).join(', ')
  out.push(`| ${d} | ${list[0].github} | ${list.length} | ${mods} |`)
}
out.push('')

out.push('## Timeline', '', '| Date | Developer | Module | Session | Jira | Branch | PR | Status |', '| --- | --- | --- | --- | --- | --- | --- | --- |')
for (const s of sessions) {
  out.push(`| ${s.date} | ${s.developer} | ${s.module} | ${s.title} | ${s.jira.join(', ') || 'none'} | ${s.branch || 'none'} | ${s.pr || 'none'} | ${s.status || 'done'} |`)
}
out.push('')

out.push('## Sessions by module', '')
for (const [m, list] of byModule) {
  out.push(`### ${moduleLabel(m)}`, '')
  for (const s of list) {
    out.push(`#### ${s.date} · ${s.title}`, '')
    out.push(`${s.developer} (${s.github}) with ${s.tool || 'unknown tool'}. Jira: ${s.jira.join(', ') || 'none'}. Branch: ${s.branch || 'none'}. PR: ${s.pr || 'none'}. Status: ${s.status || 'done'}.`, '')
    out.push(demote(s.content), '')
  }
}

out.push('## Sessions by developer', '')
for (const [d, list] of byDev) {
  out.push(`### ${d}`, '')
  for (const s of list) out.push(`* ${s.date}, ${s.module}: ${s.title}`)
  out.push('')
}

writeFileSync(outFile, out.join('\n'))
console.log(`Wrote ${outFile} with ${sessions.length} sessions`)
